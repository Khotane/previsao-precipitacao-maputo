# 1. Definir a variável-alvo futura (Precipitação no dia seguinte t+1)
df_sorted = df.dropna(subset=['Data_Parsed']).sort_values('Data_Parsed').copy()

# Criar a coluna target: Precipitação_Amanha
df_sorted['Precipitacao_Amanha'] = df_sorted['Precipitação Total (mm)'].shift(-1)

# Remover a última linha do dataset, pois ela não tem um dia seguinte (t+1) para prever
df_model = df_sorted.dropna(subset=['Precipitacao_Amanha']).copy()

print("=== Preparação da Variável-Alvo Concluída ===")
print(f"Tamanho original da série: {len(df_sorted)} dias")
print(f"Tamanho após alinhar para t+1: {len(df_model)} dias")
display(df_model[['Data', 'Precipitação Total (mm)', 'Precipitacao_Amanha']].head())

# 1. Criar Lags (valores passados) da Precipitação diária
df_model['Precipitacao_Lag1'] = df_model['Precipitação Total (mm)']
df_model['Precipitacao_Lag2'] = df_model['Precipitação Total (mm)'].shift(1)
df_model['Precipitacao_Lag3'] = df_model['Precipitação Total (mm)'].shift(2)

# 2. Selecionar as variáveis meteorológicas do dia atual (t)
# Usaremos as colunas identificadas na correlação e análise descritiva
features_meteorologicas = [
    'Temp. Méd (°C)',
    'Humidade Méd (%)',
    'Pressão Méd (hPa)',
    'Vel. Vento Máx (km/h)'
]

# 3. Codificação de variáveis categóricas (Estação)
# 'Estacao' possui as categorias 'Chuvosa (Nov-Mar)' e 'Seca (Mai-Ago)'. Vamos converter para uma dummy (1 = Chuvosa, 0 = Seca)
df_model['Estacao_Chuvosa_Dummy'] = (df_model['Estacao'] == 'Chuvosa (Nov-Mar)').astype(int)

# 4. Reunir todas as features potenciais
features_cols = [
    'Mes_Int',
    'Estacao_Chuvosa_Dummy',
    'Precipitacao_Lag1',
    'Precipitacao_Lag2',
    'Precipitacao_Lag3'
] + features_meteorologicas

