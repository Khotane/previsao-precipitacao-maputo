# 2. Função auxiliar para calcular todas as métricas solicitadas
def calcular_metricas(observado, previsto):
    if len(observado) < 2:
        return {"MAE": np.nan, "RMSE": np.nan, "R²": np.nan, "Corr": np.nan, "N": len(observado)}

    mae = mean_absolute_error(observado, previsto)
    rmse = np.sqrt(mean_squared_error(observado, previsto))
    r2 = r2_score(observado, previsto)

    if np.std(observado) == 0 or np.std(previsto) == 0:
        corr = 0.0
    else:
        corr, _ = pearsonr(observado, previsto)

    return {"MAE": mae, "RMSE": rmse, "R²": r2, "Corr": corr, "N": len(observado)}

# 3. Definir máscaras para os subconjuntos
