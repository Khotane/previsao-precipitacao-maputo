"""### Ajuste dos Modelos SARIMAX Candidatos, Critérios de Informação e Diagnóstico de Ljung-Box

Nesta etapa, ajustamos três configurações distintas para a ordem autorregressiva e de média móvel $(p, d, q)$ do SARIMAX utilizando as variáveis exógenas meteorológicas e sazonais limpas em `X_train_exog`. Em seguida, aplicamos o teste formal de Ljung-Box para auditar os resíduos.

"""

